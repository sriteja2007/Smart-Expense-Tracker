describe('AiAdvisor Component', () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  it('renders AI Financial Advisor interface with suggested prompt chips and zero-trust policy', async () => {
    vi.mocked(FinancialApi.listAiConversations).mockResolvedValueOnce([]);

    render(
      <ToastProvider>
        <AiAdvisor currency="INR" />
      </ToastProvider>
    );

    expect(screen.getByText('AI Advisor')).toBeInTheDocument();
    expect(screen.getByText('Financial Intelligence Assistant')).toBeInTheDocument();
    expect(screen.getByText(/Zero-Trust Data Policy/i)).toBeInTheDocument();
    expect(screen.getByText('💬 Where did most of my money go this month?')).toBeInTheDocument();
    expect(screen.getByText('💬 Which categories are over budget?')).toBeInTheDocument();
    expect(screen.getByText('💬 Suggest areas where I could reduce spending.')).toBeInTheDocument();
  });

  it('sends prompt when user clicks a suggested chip and displays assistant response', async () => {
    vi.mocked(FinancialApi.listAiConversations).mockResolvedValueOnce([]);
    vi.mocked(FinancialApi.sendAiChat).mockResolvedValueOnce({
      conversationId: 'conv-new-1',
      userMessage: {
        id: 'msg-u1',
        role: 'user',
        content: 'Where did most of my money go this month?',
        timestamp: new Date().toISOString()
      },
      aiMessage: {
        id: 'msg-a1',
        role: 'model',
        content: 'Your top spending category this month is Groceries (₹12,400). You are within your budgeted targets.',
        timestamp: new Date().toISOString()
      },
      isAiGenerated: true,
      isFallback: false,
      model: 'gemini-2.5-flash',
      analysisPeriod: '2026-10-01 to 2026-10-31',
      disclaimer: 'Generated by LumaSpend AI Assistant based on your ledger activity. Not certified financial advice.'
    });

    render(
      <ToastProvider>
        <AiAdvisor currency="INR" />
      </ToastProvider>
    );

    // Click suggested prompt chip
    const chip = screen.getByText('💬 Where did most of my money go this month?');
    fireEvent.click(chip);

    await waitFor(() => {
      expect(FinancialApi.sendAiChat).toHaveBeenCalledWith(
        'Where did most of my money go this month?',
        undefined
      );
    });

    await waitFor(() => {
      expect(
        screen.getByText(/Your top spending category this month is Groceries/i)
      ).toBeInTheDocument();
      expect(screen.getByText(/Period: 2026-10-01 to 2026-10-31/i)).toBeInTheDocument();
    });
  });

  it('allows user to type a custom prompt and submit message', async () => {
    vi.mocked(FinancialApi.listAiConversations).mockResolvedValueOnce([]);
    vi.mocked(FinancialApi.sendAiChat).mockResolvedValueOnce({
      conversationId: 'conv-new-2',
      userMessage: {
        id: 'msg-u2',
        role: 'user',
        content: 'How is my restaurant spending?',
        timestamp: new Date().toISOString()
      },
      aiMessage: {
        id: 'msg-a2',
        role: 'model',
        content: 'Dining and entertainment increased by 18% compared to September.',
        timestamp: new Date().toISOString()
      },
      isAiGenerated: false,
      isFallback: true,
      model: 'rule-based-engine',
      analysisPeriod: '2026-10-01 to 2026-10-31',
      disclaimer: 'Generated by LumaSpend AI Assistant based on your ledger activity. Not certified financial advice.'
    });

    render(
      <ToastProvider>
        <AiAdvisor currency="INR" />
      </ToastProvider>
    );

    const input = screen.getByPlaceholderText(/Ask anything about your spending/i);
    fireEvent.change(input, { target: { value: 'How is my restaurant spending?' } });

    const submitBtn = screen.getByRole('button', { name: /Send/i });
    fireEvent.click(submitBtn);

    await waitFor(() => {
      expect(FinancialApi.sendAiChat).toHaveBeenCalledWith(
        'How is my restaurant spending?',
        undefined
      );
    });

    await waitFor(() => {
      expect(
        screen.getByText(/Dining and entertainment increased by 18%/i)
      ).toBeInTheDocument();
      expect(screen.getByText('Rule-Based Engine')).toBeInTheDocument();
    });
  });
});

describe('ReceiptScannerModal Component', () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  it('renders upload dropzone with supported format guidelines', () => {
    render(
      <ToastProvider>
        <ReceiptScannerModal
          open={true}
          onClose={vi.fn()}
          accounts={mockAccounts}
          categories={mockCategories}
          currency="INR"
          onTransactionCreated={vi.fn()}
        />
      </ToastProvider>
    );

    expect(screen.getByText('Receipt OCR Scanner')).toBeInTheDocument();
    expect(screen.getByText('Upload Receipt Photo')).toBeInTheDocument();
    expect(screen.getByText('JPEG, PNG, or WebP up to 5 MB')).toBeInTheDocument();
  });

  it('scans receipt image, populates review form, and requires user confirmation before transaction creation', async () => {
    const onTransactionCreated = vi.fn();
    const onClose = vi.fn();

    vi.mocked(FinancialApi.scanReceipt).mockResolvedValueOnce({
      candidateMerchant: 'Starbucks Coffee',
      candidateDateUtc: '2026-10-09T00:00:00.000Z',
      candidateAmountMinorUnits: 45000, // ₹450
      candidateCurrency: 'INR',
      confidenceScore: 92,
      rawTextPreview: 'STARBUCKS COFFEE TOTAL 450.00 DATE 09/10/2026',
      isReadable: true,
      suggestedCategoryId: 'Dining & Food'
    });

    vi.mocked(FinancialApi.createTransaction).mockResolvedValueOnce({
      id: 'tx-scanned-1',
      userId: 'usr-1',
      sourceAccountId: 'acc-checking',
      categoryId: 'cat-dining',
      amountMinorUnits: 45000,
      currency: 'INR',
      type: 'expense',
      dateUtc: '2026-10-09T00:00:00.000Z',
      description: 'Starbucks Coffee (Receipt)',
      merchantName: 'Starbucks Coffee',
      paymentMethod: 'other',
      tags: ['receipt-ocr'],
      isRecurring: false,
      status: 'completed',
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString()
    });

    render(
      <ToastProvider>
        <ReceiptScannerModal
          open={true}
          onClose={onClose}
          accounts={mockAccounts}
          categories={mockCategories}
          currency="INR"
          onTransactionCreated={onTransactionCreated}
        />
      </ToastProvider>
    );

    // Create a mock image file
    const file = new File(['fake-image-bytes'], 'starbucks.png', { type: 'image/png' });
    const fileInput = document.querySelector('input[type="file"]') as HTMLInputElement;

    // Simulate file selection
    fireEvent.change(fileInput, { target: { files: [file] } });

    // Click "Scan with OCR" button
    const scanBtn = screen.getByRole('button', { name: /Scan with OCR/i });
    fireEvent.click(scanBtn);

    // Verify scan API was called
    await waitFor(() => {
      expect(FinancialApi.scanReceipt).toHaveBeenCalledWith(file);
    });

    // Check that OCR candidates were displayed in review form
    await waitFor(() => {
      expect(screen.getByText('OCR Confidence: 92%')).toBeInTheDocument();
      expect(screen.getByDisplayValue('Starbucks Coffee')).toBeInTheDocument();
      expect(screen.getByDisplayValue('450')).toBeInTheDocument();
    });

    // CRITICAL COMPLETION GATE REQUIREMENT:
    // OCR MUST NEVER silently create a transaction without user clicking Confirm!
    expect(FinancialApi.createTransaction).not.toHaveBeenCalled();

    // Now click the explicit user confirmation button: "Confirm & Create Transaction"
    const confirmBtn = screen.getByRole('button', { name: /Confirm & Create Transaction/i });
    fireEvent.click(confirmBtn);

    await waitFor(() => {
      expect(FinancialApi.createTransaction).toHaveBeenCalledWith(
        expect.objectContaining({
          type: 'expense',
          amountMinorUnits: 45000,
          currency: 'INR',
          merchantName: 'Starbucks Coffee',
          categoryId: 'cat-dining',
          sourceAccountId: 'acc-checking'
        })
      );
      expect(onTransactionCreated).toHaveBeenCalled();
      expect(onClose).toHaveBeenCalled();
    });
  });
});
